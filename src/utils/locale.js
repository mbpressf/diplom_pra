export function getCurrencyConfig(locale = 'ru') {
  return locale === 'en'
    ? { numberLocale: 'en-US', currency: 'USD' }
    : { numberLocale: 'ru-RU', currency: 'RUB' }
}

export function tFor(locale = 'ru', key, params = {}) {
  const dictionary = messages[locale] || messages.ru
  const fallback = messages.ru[key] || key
  const template = dictionary[key] || fallback
  return Object.entries(params).reduce((acc, [name, value]) => acc.replaceAll(`{${name}}`, String(value)), template)
}

export function normalizeRate(rate) {
  return Number.isFinite(Number(rate)) && Number(rate) > 0 ? Number(rate) : FALLBACK_USD_TO_RUB
}

export function convertFromRub(amount, locale = 'ru', usdToRubRate = FALLBACK_USD_TO_RUB) {
  const numericAmount = Number(amount) || 0
  if (locale !== 'en') return numericAmount
  return numericAmount / normalizeRate(usdToRubRate)
}

export function convertToRub(amount, locale = 'ru', usdToRubRate = FALLBACK_USD_TO_RUB) {
  const numericAmount = Number(amount) || 0
  if (locale !== 'en') return numericAmount
  return numericAmount * normalizeRate(usdToRubRate)
}

export function formatMoneyFromRub(amount, locale = 'ru', usdToRubRate = FALLBACK_USD_TO_RUB) {
  const { numberLocale, currency } = getCurrencyConfig(locale)
  const convertedAmount = convertFromRub(amount, locale, usdToRubRate)
  return formatMoneyDisplay(convertedAmount, locale, currency)
}

export function formatMoneyDisplay(amount, locale = 'ru', currencyOverride) {
  const { numberLocale, currency } = getCurrencyConfig(locale)
  return new Intl.NumberFormat(numberLocale, {
    style: 'currency',
    currency: currencyOverride || currency,
    maximumFractionDigits: 2,
  }).format(Number(amount) || 0)
}

export function formatRateValue(rate, locale = 'ru') {
  const numberLocale = locale === 'en' ? 'en-US' : 'ru-RU'
  return new Intl.NumberFormat(numberLocale, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 4,
  }).format(normalizeRate(rate))
}

export function formatShortDate(dateString, locale = 'ru') {
  if (!dateString) return ''
  const parsed = new Date(dateString)
  if (Number.isNaN(parsed.getTime())) return dateString
  return new Intl.DateTimeFormat(locale === 'en' ? 'en-US' : 'ru-RU', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  }).format(parsed)
}
